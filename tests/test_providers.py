HANG = object()


def step(code="", thinking="step", language="python") -> str:
    return json.dumps({"thinking": thinking, "code": code, "language": language})


DONE_TEXT = step("", "DONE")


class FakeChat:
    """Fake ChatClient: returns the predefined texts in order, streaming them in small chunks."""

    def __init__(self, registry, spec):
        self.registry, self.spec = registry, spec

    async def stream(self, system, messages, max_tokens, on_text):
        self.registry.calls.append(self.spec.key)
        text = self.registry.texts.pop(0) if self.registry.texts else DONE_TEXT
        if text is HANG:
            await on_text('{"thinking": "slow", "code": "print(')
            await asyncio.sleep(60)
        for i in range(0, len(text), 5):
            await on_text(text[i:i + 5])
            await asyncio.sleep(0)
        return ChatResult(text, "end", "stop", {})


class RecordingRegistry(ProviderRegistry):
    """The real registry (config + preflight) but create() returns a FakeChat and records which model was used."""

    def __init__(self, texts, **kw):
        base = fake_registry(**kw)
        super().__init__(base.settings, transport=base._transport)
        self.texts, self.created, self.calls = list(texts), [], []

    def create(self, spec):
        missing = self.settings.missing_config(spec.provider)
        if missing:
            raise ProviderError(NOT_CONFIGURED, spec.provider, missing)
        self.created.append(spec.key)
        return FakeChat(self, spec)


