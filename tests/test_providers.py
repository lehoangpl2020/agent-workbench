def test_ollama_stream_is_cancellable():
    async def body():
        yield b'{"message": {"content": "{\\"thinking\\""}, "done": false}\n'
        await asyncio.sleep(60)
        yield b""

    def handler(request):
        return httpx.Response(200, content=body())

    async def go():
        chat = ollama_chat(handler)
        got = asyncio.Event()

        async def on_text(t):
            got.set()
        task = asyncio.create_task(chat.stream("SYS", [{"role": "user", "content": "x"}], 10, on_text))
        await asyncio.wait_for(got.wait(), 5)
        t0 = time.monotonic()
        task.cancel()
        with pytest.raises(asyncio.CancelledError):
            await task
        return time.monotonic() - t0
    assert asyncio.run(go()) < 2


