def sse(*events) -> bytes:
    return "".join(f"event: {e['type']}\ndata: {json.dumps(e)}\n\n" for e in events).encode()


def openai_chat(handler, model="gpt-6.2-sol"):
    spec = find("openai", model)
    http = httpx.AsyncClient(transport=httpx.MockTransport(handler))
    return OpenAIChat(spec, http, "https://api.openai.test/v1", "test-openai-key")


def collect(chat, messages=None):
    chunks: list[str] = []

    async def on_text(t):
        chunks.append(t)

    async def go():
        return await chat.stream("SYS", messages or [{"role": "user", "content": "hi"}], 1234, on_text)
    return asyncio.run(go()), chunks


def test_openai_request_shape_and_stream():
    seen = {}

    def handler(request):
        seen["url"] = str(request.url)
        seen["auth"] = request.headers.get("authorization")
        seen["body"] = json.loads(request.content)
        text = step("print(1)")
        return httpx.Response(200, content=sse(
            {"type": "response.created", "response": {"status": "in_progress"}},
            {"type": "response.output_text.delta", "delta": text[:10]},
            {"type": "response.output_text.delta", "delta": text[10:]},
            {"type": "response.completed", "response": {"status": "completed", "usage": {
                "input_tokens": 50, "output_tokens": 20, "output_tokens_details": {"reasoning_tokens": 7}}}},
        ), headers={"content-type": "text/event-stream"})

    result, chunks = collect(openai_chat(handler), [
        {"role": "user", "content": "task"}, {"role": "assistant", "content": "{}"}, {"role": "user", "content": "fix"}])
    body = seen["body"]
    assert seen["url"] == "https://api.openai.test/v1/responses"
    assert seen["auth"] == "Bearer test-openai-key"
    assert body["model"] == "gpt-6.2-sol" and body["instructions"] == "SYS"
    assert body["max_output_tokens"] == 1234 and body["stream"] is True and body["store"] is False
    assert body["reasoning"] == {"effort": "low"}
    assert body["text"]["format"]["type"] == "json_schema" and body["text"]["format"]["strict"] is True
    assert [m["role"] for m in body["input"]] == ["user", "assistant", "user"]
    # Do not carry Anthropic-style parameters over
    for key in ("system", "max_tokens", "temperature", "messages"):
        assert key not in body
    assert len(chunks) == 2 and result.text == step("print(1)") and result.stop == "end"
    assert result.usage == {"input_tokens": 50, "output_tokens": 20, "reasoning_tokens": 7}


